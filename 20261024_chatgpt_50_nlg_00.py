import numpy as np
from tensorflow.keras.preprocessing.sequence import pad_sequences

seed_text = "주먹도끼는"
next_words = 10
max_sequence_len = 14  # 모델의 input_shape과 동일하게 설정

# vectorizer의 단어 사전(Vocabulary) 가져오기
vocab = vectorizer.get_vocabulary()

for _ in range(next_words):
    # vectorizer를 사용하여 seed_text를 숫자로 변환
    token_list = vectorizer([seed_text]).numpy()[0]
    # 입력 형태에 맞게 패딩 처리
    token_list = pad_sequences([token_list], maxlen=max_sequence_len, padding='pre')

    # 다음 단어 예측
    predicted_index = np.argmax(model.predict(token_list, verbose=0), axis=-1)[0]

    # 예측된 인덱스로 단어 찾기 (사전 범위를 벗어나지 않도록 방어 코드 추가)
    output_word = ""
    if predicted_index < len(vocab):
        output_word = vocab[predicted_index]

    # OOV(알 수 없는 단어)나 공백 패딩 토큰이 나오면 멈추거나 추가하지 않음
    if output_word == "" or output_word == "[UNK]":
        break

    seed_text += " " + output_word

print(seed_text)